def main() -> None:
    out_path = Path(__file__).with_name("scholarships_gemini_batch2.csv")
    with out_path.open("w", encoding="utf-8", newline="\n") as f:
        writer = csv.writer(f, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        writer.writerow(HEADER)
        for row in ROWS:
            writer.writerow([row.get(col, "") for col in HEADER])

    rows, structural = load_csv_strict(str(out_path))
    assert structural.get("header_valid"), structural
    assert not structural.get("rejected_rows"), structural.get("rejected_rows")
    failures = []
    for row in rows:
        result = validate_import_row(row)
        if result.get("status") == "invalid":
            failures.append((row.get("title"), result.get("error")))
    if failures:
        for title, err in failures:
            print(f"INVALID: {title}: {err}", file=sys.stderr)
        sys.exit(1)
    print(f"OK: {len(rows)} rows -> {out_path}")


if __name__ == "__main__":
    main()
